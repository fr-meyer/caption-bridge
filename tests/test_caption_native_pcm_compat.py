@pytest.mark.parametrize("native_format", GOLDEN)
def test_audioop_cpython_golden_bytes_state_and_arbitrary_frame_chunks(native_format):
    rate, channels = native_format
    pcm = b"".join((((i * 7919 + i * i * 31 + channel * 104729) % 65536) - 32768)
                   .to_bytes(2, "little", signed=True)
                   for i in range(257) for channel in range(channels))
    converter = AsrPcmConverter(ASR_RATE)
    whole = converter.convert(pcm, native_format)
    length, expected_hash, state = GOLDEN[native_format]
    assert len(whole) == length
    assert hashlib.sha256(whole).hexdigest() == expected_hash
    assert converter.state == state
    chunked = AsrPcmConverter(ASR_RATE)
    output, offset, index = [], 0, 0
    frame_sizes = (1, 2, 17, 31, 3)
    while offset < len(pcm):
        end = offset + frame_sizes[index % len(frame_sizes)] * 2 * channels
        output.append(chunked.convert(pcm[offset:end], native_format))
        offset, index = end, index + 1
    assert b"".join(output) == whole
    assert chunked.state == converter.state
    chunked.clear()
    assert chunked.state is None
    assert chunked.convert(pcm, native_format) == whole


def test_conversion_remains_fail_closed_if_runtime_dependency_is_missing(monkeypatch):
    original = builtins.__import__
    def missing(name, *args, **kwargs):
        if name == "audioop":
            raise ImportError("SYNTHETIC_DEPENDENCY_FAILURE")
        return original(name, *args, **kwargs)
    monkeypatch.setattr(builtins, "__import__", missing)
    for native_format in ((48000, 1), (16000, 2)):
        with pytest.raises(PcmProtocolError, match="conversion_unavailable"):
            AsrPcmConverter(ASR_RATE).convert(bytes(8), native_format)
    pcm = bytes(8)
    assert AsrPcmConverter(ASR_RATE).convert(pcm, (16000, 1)) is pcm


def test_audioop_backport_is_exactly_locked_only_after_stdlib_removal():
    project = tomllib.loads((ROOT / "pyproject.toml").read_text())
    lock = tomllib.loads((ROOT / "uv.lock").read_text())
    dependency, = (Requirement(value) for value in project["project"]["dependencies"]
                   if Requirement(value).name == "audioop-lts")
    assert str(dependency.specifier) == "==0.2.2"
    assert dependency.marker is not None
    for version, required in (("3.11", False), ("3.12", False), ("3.13", True), ("3.14", True)):
        assert dependency.marker.evaluate({"python_version": version}) is required
    package, = (value for value in lock["package"] if value["name"] == "audioop-lts")
    assert package["version"] == "0.2.2"
    assert package.get("dependencies", []) == []
    assert package["source"] == {"registry": "https://pypi.org/simple"}
